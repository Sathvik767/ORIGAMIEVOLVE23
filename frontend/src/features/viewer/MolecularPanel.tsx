const MolecularScene3D = lazy(() => import("./MolecularScene3D").then((m) => ({ default: m.MolecularScene3D })));

const STATUS_TEXT: Record<string, string> = {
  awaiting_configuration: "Topology uploaded; the oxDNA configuration (coordinates) has not been uploaded yet.",
  validating: "Validating the structure files…",
  converting: "Converting caDNAno to oxDNA with tacoxDNA…",
  topology_only:
    "caDNAno topology only: the file has no coordinates or sequences. Convert it with tacoxDNA (lattice stated by you, scaffold sequence from the linked design) to get coordinates.",
  invalid: "The structure files failed validation, so no coordinates are shown.",
};

/** Why molecular mode isn't available for this structure (shown above the schematic fallback). */
export function StructureStatus({ structure }: { structure: StructureOut }) {
  const errors = (structure.issues ?? []).filter((i) => i.severity === "error");
  return (
    <Callout role="status" tone="warning" icon={<TriangleAlert />}>
      <p>
        <strong>Structure “{structure.name}” ({structure.format}):</strong> {STATUS_TEXT[structure.status] ?? structure.status}
        {structure.design_id ? " Showing the schematic instead." : ""}
      </p>
      {structure.summary && structure.format === "cadnano" && (
        <p className="mt-1 font-mono text-xs">
          {String(structure.summary.helices)} helices · {String(structure.summary.scaffold_strands)} scaffold strand(s) ·{" "}
          {String(structure.summary.staple_strands)} staples · {String(structure.summary.scaffold_crossovers)} scaffold /{" "}
          {String(structure.summary.staple_crossovers)} staple crossovers · array length {String(structure.summary.array_length)} (
          {String(structure.summary.lattice_hint)})
        </p>
      )}
      {errors.length > 0 && (
        <ul className="mt-2 list-disc pl-5 text-xs">
          {errors.slice(0, 5).map((i, k) => (
            <li key={k}>
              <span className="font-mono">{String(i.code)}</span> {String(i.message)}
              {i.location ? ` (${String(i.location)})` : ""}
            </li>
          ))}
        </ul>
      )}
      {structure.conversion?.error ? <p className="mt-1 text-xs">Conversion: {String(structure.conversion.error)}</p> : null}
    </Callout>
  );
}

function originText(structure: StructureOut): string {
  const sim = structure.simulation;
  return structure.origin === "simulated"
    ? `Simulated with oxDNA: ${String(sim?.protocol)} protocol, ${String(sim?.steps)} steps (output of a simulation run, not experimental data)`
    : structure.origin === "generated"
      ? `Generated by ${String(structure.conversion?.tool)} from caDNAno (lattice: ${String(structure.conversion?.lattice)}); initial geometry, not relaxed or simulated`
      : "Imported: coordinates as stored in the uploaded oxDNA files";
}

/** The molecular scene in the shared canvas card (floating toolbar, mode switch, legend overlay). */
export function MolecularView({
  structure,
  geometry,
  sceneRef,
  jobId,
  modeToggle,
}: {
  structure: StructureOut;
  geometry: MolecularGeometry;
  sceneRef: RefObject<SceneHandle | null>;
  jobId: string;
  modeToggle: ReactNode;
}) {
  const colors = useSceneColors();
  const placeholder = (structure.issues ?? []).some((i) => i.code === "W_NONHELICAL_GEOMETRY");
  return (
    <div className="space-y-4">
      {placeholder && (
        <Callout role="alert" tone="danger" icon={<TriangleAlert />}>
          <strong>Not a molecular structure.</strong> Every strand in this file is a straight line, which double-helical DNA never
          is. These are most likely placeholder coordinates; do not interpret them as a DNA origami shape.
        </Callout>
      )}
      <CanvasCard
        headingId="molecular-heading"
        title="3D view: molecular"
        sceneRef={sceneRef}
        modeToggle={modeToggle}
        note={
          <p role="note" className="rounded-lg border border-info/30 bg-surface/90 px-3 py-1.5 text-xs text-fg shadow-sm backdrop-blur">
            <strong>Molecular coordinates from an oxDNA file, shown as stored</strong> (only translated to the centre).
            <span className="mt-0.5 block font-semibold text-info">{originText(structure)}.</span> A fitness score does not show that
            this structure folds.
          </p>
        }
        legend={
          <ul aria-label="Molecular legend" className="flex flex-wrap gap-x-4 gap-y-1">
            <Swatch color={MOLECULAR_COLORS.scaffold}>scaffold (verified by sequence)</Swatch>
            <Swatch color={MOLECULAR_COLORS.staple}>staple (verified by sequence)</Swatch>
            <Swatch color={MOLECULAR_COLORS.unassigned}>strand without verified identity</Swatch>
            {geometry.annotated_job_id && (
              <>
                <Swatch color={MOLECULAR_COLORS.variantSelected}>optimizer chose a supplied variant</Swatch>
                <Swatch color={MOLECULAR_COLORS.variantIncompatible}>variant length differs from modelled strand</Swatch>
              </>
            )}
          </ul>
        }
        footer="One sphere per nucleotide (centre of mass), lines join bonded neighbours. Drag to rotate · scroll to zoom · right-drag to pan."
      >
        <ErrorBoundary
          key={structure.id}
          fallback={(e) => (
            <p role="alert" className="p-4 pt-24 text-sm text-danger">
              3D rendering is unavailable in this browser ({e.message}). Check that WebGL is enabled.
            </p>
          )}
        >
          <Suspense
            fallback={
              <div className="absolute inset-0 p-6 pt-24">
                <span className="sr-only">Loading 3D renderer…</span>
                <Skeleton className="h-full w-full rounded-lg" />
              </div>
            }
          >
            {/* key: switching structure (or job annotation) remounts the scene and releases GPU resources */}
            <MolecularScene3D key={`${structure.id}:${jobId}`} ref={sceneRef} geometry={geometry} background={colors.background} />
          </Suspense>
        </ErrorBoundary>
      </CanvasCard>
    </div>
  );
}

/** Structure facts, strand mapping and variant notes (side panel). */
export function StructureInfo({ structure, geometry }: { structure: StructureOut; geometry: MolecularGeometry }) {
  const s = structure.summary ?? {};
  const extent = Array.isArray(s.extent) ? (s.extent as number[]).map((v) => (v * geometry.length_unit_nm).toFixed(1)) : null;
  const mapping = structure.mapping;
  const variants = geometry.strands.filter((st) => st.variant && !st.variant.is_original);
  const incompatible = variants.filter((st) => !st.variant!.length_compatible);
  const warnings = (structure.issues ?? []).filter((i) => i.severity === "warning");
  const tools = useQuery({ queryKey: ["structure-tools"], queryFn: api.getStructureTools, staleTime: 60_000 });

  return (
    <Card as="aside" title="Structure" icon={<Atom className="size-4" />} bodyClassName="space-y-4 p-5">
      <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1.5 text-sm">
        <dt className="text-muted">Name</dt>
        <dd className="break-all">{structure.name}</dd>
        <dt className="text-muted">Nucleotides</dt>
        <dd className="font-mono">{geometry.nucleotides}</dd>
        <dt className="text-muted">Strands</dt>
        <dd className="font-mono">
          {geometry.strands.length}
          {s.circular_strands ? ` (${String(s.circular_strands)} circular)` : ""}
        </dd>
        {extent && (
          <>
            <dt className="text-muted">Extent</dt>
            <dd className="font-mono">{extent.join(" × ")} nm</dd>
          </>
        )}
        <dt className="text-muted">Units</dt>
        <dd className="text-xs">oxDNA (1 unit = {geometry.length_unit_nm} nm)</dd>
      </dl>
      {structure.design_id ? (
        <div className="border-t border-border pt-3 text-sm">
          <p>
            Strand mapping to{" "}
            <Link to={`/designs/${structure.design_id}`} className="text-primary underline">
              linked design
            </Link>
            : <strong>{String(mapping?.status ?? "not computed")}</strong>
          </p>
          {mapping && (
            <p className="mt-1 text-xs text-muted">
              Scaffold {mapping.scaffold_strand != null ? "matched" : "not matched"} ·{" "}
              {Object.keys((mapping.staples as Record<string, number>) ?? {}).length} staples matched ·{" "}
              {(mapping.unmatched as string[] | undefined)?.length ?? 0} unmatched · {(mapping.ambiguous as string[] | undefined)?.length ?? 0}{" "}
              ambiguous (exact, unique sequence matches only)
            </p>
          )}
        </div>
      ) : (
        <p className="border-t border-border pt-3 text-xs text-muted">
          Not linked to a design, so strand identities (scaffold vs staple) are not assigned.
        </p>
      )}
      {geometry.annotated_job_id && (
        <div className="border-t border-border pt-3 text-xs text-accent">
          <p>
            {variants.length} verified staple(s) use a supplied variant
            {incompatible.length ? `; ${incompatible.length} differ in length from the modelled strand` : ""}.
          </p>
          <p className="mt-1">
            The structure was modelled with the original sequences; variants are annotations only. A fitness score is a computational proxy
            and does not show that this structure, or the variant design, folds.
          </p>
        </div>
      )}
      <p className="border-t border-border pt-3 text-xs text-muted">
        oxDNA relaxation/simulation:{" "}
        {tools.data?.oxdna.available
          ? "available (POST /structures/{id}/simulate)."
          : tools.data
            ? `not available. ${tools.data.oxdna.message ?? ""} See tools/oxdna/README.md.`
            : "checking…"}
      </p>
      {warnings.length > 0 && (
        <ul className="border-t border-border pt-3 text-xs text-accent">
          {warnings.map((w, k) => (
            <li key={k}>{String(w.message)}</li>
          ))}
        </ul>
      )}
    </Card>
  );
}
