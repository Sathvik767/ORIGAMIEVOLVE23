import { useQuery } from "@tanstack/react-query";
import { lazy, Suspense, type RefObject } from "react";
import { Link } from "react-router";

import { api, type MolecularGeometry, type StructureOut } from "../../api/client";
import { ErrorBoundary } from "../../components/ErrorBoundary";
import { MOLECULAR_COLORS, type SceneHandle } from "./sceneTypes";

const MolecularScene3D = lazy(() => import("./MolecularScene3D").then((m) => ({ default: m.MolecularScene3D })));

const STATUS_TEXT: Record<string, string> = {
  awaiting_configuration: "Topology uploaded; the oxDNA configuration (coordinates) has not been uploaded yet.",
  validating: "Validating the structure files…",
  converting: "Converting caDNAno to oxDNA with tacoxDNA…",
  topology_only:
    "caDNAno topology only: the file has no coordinates or sequences. Convert it with tacoxDNA (lattice stated by you, scaffold sequence from the linked design) to get coordinates.",
  invalid: "The structure files failed validation, so no coordinates are shown.",
};

/** Banner above the viewer: molecular/schematic switch, or why molecular mode isn't available. */
export function StructureStatus({
  structure,
  mode,
  onMode,
  available,
}: {
  structure: StructureOut;
  mode: "molecular" | "schematic";
  onMode: (m: "molecular" | "schematic") => void;
  available: boolean;
}) {
  if (available) {
    return (
      <div role="radiogroup" aria-label="View mode" className="flex flex-wrap gap-4 rounded-lg border border-slate-200 bg-white px-5 py-3 text-sm shadow-sm">
        <span className="text-slate-600">View:</span>
        <label className="flex items-center gap-1.5">
          <input type="radio" name="view-mode" checked={mode === "molecular"} onChange={() => onMode("molecular")} />
          Molecular (oxDNA coordinates)
        </label>
        <label className="flex items-center gap-1.5">
          <input type="radio" name="view-mode" checked={mode === "schematic"} onChange={() => onMode("schematic")} />
          Schematic (index space)
        </label>
      </div>
    );
  }
  const errors = (structure.issues ?? []).filter((i) => i.severity === "error");
  return (
    <div role="status" className="rounded-lg border border-amber-200 bg-amber-50 px-5 py-3 text-sm text-amber-900">
      <p>
        <strong>Structure “{structure.name}” ({structure.format}):</strong>{" "}
        {STATUS_TEXT[structure.status] ?? structure.status}
        {structure.design_id ? " Showing the schematic instead." : ""}
      </p>
      {structure.summary && structure.format === "cadnano" && (
        <p className="mt-1 text-xs">
          {String(structure.summary.helices)} helices · {String(structure.summary.scaffold_strands)} scaffold strand(s) ·{" "}
          {String(structure.summary.staple_strands)} staples · {String(structure.summary.scaffold_crossovers)} scaffold /{" "}
          {String(structure.summary.staple_crossovers)} staple crossovers · array length {String(structure.summary.array_length)} (
          {String(structure.summary.lattice_hint)})
        </p>
      )}
      {errors.length > 0 && (
        <ul className="mt-2 list-disc pl-5 text-xs">
          {errors.slice(0, 5).map((i, k) => (
            <li key={k}>
              <span className="font-mono">{String(i.code)}</span> {String(i.message)}
              {i.location ? ` (${String(i.location)})` : ""}
            </li>
          ))}
        </ul>
      )}
      {structure.conversion?.error ? <p className="mt-1 text-xs">Conversion: {String(structure.conversion.error)}</p> : null}
    </div>
  );
}

export function MolecularPanel({
  structure,
  geometry,
  sceneRef,
  jobId,
}: {
  structure: StructureOut;
  geometry: MolecularGeometry;
  sceneRef: RefObject<SceneHandle | null>;
  jobId: string;
}) {
  const s = structure.summary ?? {};
  const extent = Array.isArray(s.extent) ? (s.extent as number[]).map((v) => (v * geometry.length_unit_nm).toFixed(1)) : null;
  const mapping = structure.mapping;
  const variants = geometry.strands.filter((st) => st.variant && !st.variant.is_original);
  const incompatible = variants.filter((st) => !st.variant!.length_compatible);
  const warnings = (structure.issues ?? []).filter((i) => i.severity === "warning");
  const sim = structure.simulation;
  const origin =
    structure.origin === "simulated"
      ? `Simulated with oxDNA: ${String(sim?.protocol)} protocol, ${String(sim?.steps)} steps (output of a simulation run, not experimental data)`
      : structure.origin === "generated"
        ? `Generated by ${String(structure.conversion?.tool)} from caDNAno (lattice: ${String(structure.conversion?.lattice)}); initial geometry, not relaxed or simulated`
        : "Imported: coordinates as stored in the uploaded oxDNA files";
  const placeholder = (structure.issues ?? []).some((i) => i.code === "W_NONHELICAL_GEOMETRY");
  const tools = useQuery({ queryKey: ["structure-tools"], queryFn: api.getStructureTools, staleTime: 60_000 });

  return (
    <div className="grid gap-6 lg:grid-cols-[2fr_1fr]">
      <section aria-labelledby="molecular-heading" className="min-w-0 rounded-lg border border-slate-200 bg-white p-5 shadow-sm">
        <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
          <h2 id="molecular-heading" className="text-lg font-semibold text-slate-800">
            3D view: molecular
          </h2>
          <div className="flex gap-2 text-xs">
            <button type="button" onClick={() => sceneRef.current?.zoom(1.25)} className="rounded border border-slate-300 px-2 py-0.5">
              Zoom in
            </button>
            <button type="button" onClick={() => sceneRef.current?.zoom(0.8)} className="rounded border border-slate-300 px-2 py-0.5">
              Zoom out
            </button>
            <button type="button" onClick={() => sceneRef.current?.reset()} className="rounded border border-slate-300 px-2 py-0.5">
              Reset view
            </button>
          </div>
        </div>
        <p role="note" className="mb-3 rounded border border-sky-200 bg-sky-50 px-3 py-2 text-xs text-sky-900">
          <strong>Molecular coordinates from an oxDNA file, shown as stored</strong> (only translated to the centre).
          <span className="mt-1 block font-semibold">{origin}.</span> A fitness score does not show that this structure folds.
        </p>
        {placeholder && (
          <p role="alert" className="mb-3 rounded border border-red-200 bg-red-50 px-3 py-2 text-xs text-red-800">
            <strong>Not a molecular structure.</strong> Every strand in this file is a straight line, which double-helical
            DNA never is. These are most likely placeholder coordinates; do not interpret them as a DNA origami shape.
          </p>
        )}
        <div className="h-[460px] overflow-hidden rounded border border-slate-100">
          <ErrorBoundary
            key={structure.id}
            fallback={(e) => (
              <p role="alert" className="p-4 text-sm text-red-800">
                3D rendering is unavailable in this browser ({e.message}). Check that WebGL is enabled.
              </p>
            )}
          >
            <Suspense fallback={<p className="p-4 text-sm text-slate-500">Loading 3D renderer…</p>}>
              {/* key: switching structure (or job annotation) remounts the scene and releases GPU resources */}
              <MolecularScene3D key={`${structure.id}:${jobId}`} ref={sceneRef} geometry={geometry} />
            </Suspense>
          </ErrorBoundary>
        </div>
        <p className="mt-2 text-xs text-slate-500">
          One sphere per nucleotide (centre of mass), lines join bonded neighbours. Drag to rotate · scroll to zoom · right-drag to pan.
        </p>
        <ul aria-label="Molecular legend" className="mt-2 flex flex-wrap gap-x-4 gap-y-1 text-xs text-slate-600">
          <li><span className="mr-1 inline-block h-2 w-4 align-middle" style={{ background: MOLECULAR_COLORS.scaffold }} />scaffold (verified by sequence)</li>
          <li><span className="mr-1 inline-block h-2 w-4 align-middle" style={{ background: MOLECULAR_COLORS.staple }} />staple (verified by sequence)</li>
          <li><span className="mr-1 inline-block h-2 w-4 align-middle" style={{ background: MOLECULAR_COLORS.unassigned }} />strand without verified identity</li>
          {geometry.annotated_job_id && (
            <>
              <li><span className="mr-1 inline-block h-2 w-4 align-middle" style={{ background: MOLECULAR_COLORS.variantSelected }} />optimizer chose a supplied variant</li>
              <li><span className="mr-1 inline-block h-2 w-4 align-middle" style={{ background: MOLECULAR_COLORS.variantIncompatible }} />variant length differs from modelled strand</li>
            </>
          )}
        </ul>
      </section>

      <aside aria-labelledby="structure-info-heading" className="space-y-4 rounded-lg border border-slate-200 bg-white p-5 shadow-sm">
        <h2 id="structure-info-heading" className="text-lg font-semibold text-slate-800">
          Structure
        </h2>
        <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1 text-sm">
          <dt className="text-slate-500">Name</dt>
          <dd className="break-all">{structure.name}</dd>
          <dt className="text-slate-500">Nucleotides</dt>
          <dd>{geometry.nucleotides}</dd>
          <dt className="text-slate-500">Strands</dt>
          <dd>{geometry.strands.length}{s.circular_strands ? ` (${String(s.circular_strands)} circular)` : ""}</dd>
          {extent && (
            <>
              <dt className="text-slate-500">Extent</dt>
              <dd>{extent.join(" × ")} nm</dd>
            </>
          )}
          <dt className="text-slate-500">Units</dt>
          <dd className="text-xs">oxDNA (1 unit = {geometry.length_unit_nm} nm)</dd>
        </dl>
        {structure.design_id ? (
          <div className="border-t border-slate-100 pt-3 text-sm">
            <p>
              Strand mapping to{" "}
              <Link to={`/designs/${structure.design_id}`} className="underline">
                linked design
              </Link>
              : <strong>{String(mapping?.status ?? "not computed")}</strong>
            </p>
            {mapping && (
              <p className="mt-1 text-xs text-slate-600">
                Scaffold {mapping.scaffold_strand != null ? "matched" : "not matched"} ·{" "}
                {Object.keys((mapping.staples as Record<string, number>) ?? {}).length} staples matched ·{" "}
                {(mapping.unmatched as string[] | undefined)?.length ?? 0} unmatched · {(mapping.ambiguous as string[] | undefined)?.length ?? 0} ambiguous
                (exact, unique sequence matches only)
              </p>
            )}
          </div>
        ) : (
          <p className="border-t border-slate-100 pt-3 text-xs text-slate-600">
            Not linked to a design, so strand identities (scaffold vs staple) are not assigned.
          </p>
        )}
        {geometry.annotated_job_id && (
          <div className="border-t border-slate-100 pt-3 text-xs text-amber-900">
            <p>
              {variants.length} verified staple(s) use a supplied variant
              {incompatible.length ? `; ${incompatible.length} differ in length from the modelled strand` : ""}.
            </p>
            <p className="mt-1">
              The structure was modelled with the original sequences; variants are annotations only. A fitness score is a
              computational proxy and does not show that this structure, or the variant design, folds.
            </p>
          </div>
        )}
        <p className="border-t border-slate-100 pt-3 text-xs text-slate-600">
          oxDNA relaxation/simulation:{" "}
          {tools.data?.oxdna.available
            ? "available (POST /structures/{id}/simulate)."
            : tools.data
              ? `not available. ${tools.data.oxdna.message ?? ""} See tools/oxdna/README.md.`
              : "checking…"}
        </p>
        {warnings.length > 0 && (
          <ul className="border-t border-slate-100 pt-3 text-xs text-amber-800">
            {warnings.map((w, k) => (
              <li key={k}>{String(w.message)}</li>
            ))}
          </ul>
        )}
      </aside>
    </div>
  );
}
